/**
 * Autopilot: clear stale tool output from agent requests in flight, without
 * ever costing more than it saves.
 *
 * Why this and not the proxy's general strategies: replayed over 33 real
 * Claude Code sessions with prompt-cache pricing, the general trim saved 6.7%
 * overall but made one session 13% MORE expensive, because every change to
 * history the cache already holds re-bills everything after it at the write
 * rate. Most of the bill sits in long sessions (94% of input cost came from
 * requests above 200k tokens), so the win is real, but only if each change
 * pays for its cache rewrite.
 *
 * The rules, modelled on the microcompact logic Claude Code ships (and keeps
 * switched off by a server flag), tightened for "never worse":
 *
 *  1. Only output of read-only, re-runnable tools is eligible (file reads,
 *     shell, search, web fetch). Answers the user gave, subagent reports and
 *     MCP results are never touched.
 *  2. The most recent `keepRecent` tool results always stay.
 *  3. Clearing happens in batches of at least `minClearTokens`, so each cache
 *     rewrite buys a lot.
 *  4. A cleared result stays cleared on every later request (ids are
 *     remembered, across restarts), so the prefix is byte-stable between
 *     batches and the cache keeps hitting.
 *  5. By default a batch is taken ONLY when the cache is cold anyway (idle
 *     longer than the request's own cache TTL), because the whole prompt is
 *     re-written on that request regardless, so clearing costs nothing and
 *     every later request is smaller. That makes it never-worse by
 *     construction, and measured: replaying every Claude Code session on the
 *     author's machine through this class, with real timestamps and cache
 *     pricing, it saved 9.8% of cache-weighted input cost (9.2% of raw input
 *     tokens, up to 37.7% in one long session) and made no session worse.
 *     Clearing on a warm cache when the saving "should" repay the rewrite
 *     (`paybackSafety` > 0) added 0.1% and made one session 0.13% worse: the
 *     future is not knowable, so it is off unless asked for.
 *
 * The model sees a one-line note in place of the output and can simply re-run
 * the tool; the file, command or URL is still in the tool call.
 */

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { estimateTokens } from "./tokens.js";

/** Tools whose output can be regenerated by calling them again (read-only or re-runnable). */
export const CLEARABLE_TOOLS = new Set([
  // Claude Code
  "Read", "Bash", "BashOutput", "Grep", "Glob", "LS", "WebFetch", "WebSearch", "NotebookRead",
  // Codex and other OpenAI-API agents. Codex's code mode runs every tool from
  // one `exec` cell and polls long commands with `wait` (as Bash/BashOutput).
  "shell", "exec_command", "local_shell", "read_file", "list_dir", "grep_search", "file_search", "web_search", "exec", "wait",
  // Gemini CLI
  "read_many_files", "run_shell_command", "glob", "search_file_content", "list_directory", "web_fetch", "google_web_search",
  // Cursor's agent
  "Shell", "ReadFile", "rg", "run_terminal_cmd", "codebase_search", "SemanticSearch", "ReadLints", "AwaitShell",
]);

/** Tokens billed for one image inside a tool result (a full-size screenshot is ~1.6k on Claude). */
const IMAGE_TOKENS = 1600;

export interface AutoClearOptions {
  /** Most recent tool results that always stay. Default 3. */
  keepRecent?: number;
  /** Smallest batch worth a cache rewrite. Default 20,000 tokens. */
  minClearTokens?: number;
  /**
   * Warm-cache rule: clear only if the saving over the requests still to come
   * repays the rewrite this many times over. Requests still to come are
   * estimated as the number already made in this conversation. Default 0:
   * warm clearing off, cold cache only (the never-worse setting).
   */
  paybackSafety?: number;
  /**
   * Where cleared ids persist so a restart does not un-clear (and re-bill)
   * them, with each conversation's last request time so a restart does not
   * mistake a warm cache for a cold one.
   */
  statePath?: string;
  /**
   * Treat a conversation this instance has no record of as warm-cached (so
   * nothing is cleared on it). Both the proxy and the in-process wrapper turn
   * this on: a wrapper in a fresh process cannot know whether another process
   * just sent the conversation, and a restarted proxy cannot know either
   * unless the conversation's last request time was persisted (statePath).
   * Calling a warm cache cold pays a full rewrite; calling a cold one warm
   * only delays a free clearing to the next idle gap. Off here so a bare
   * AutoClearer (the savings replay) keeps its first-request-is-cold model.
   */
  unseenIsWarm?: boolean;
}

export interface AutoClearResult {
  changed: boolean;
  /** Results cleared by this request's new batch (0 when none was taken). */
  newlyCleared: number;
  /** Tokens removed from this request, old batches included. */
  tokensRemoved: number;
  cold: boolean;
  reason: string;
  /** Index of the first message rewritten on this request (the cache breaks from here), or -1. */
  firstChanged: number;
  /** Ids this request cleared for the first time. */
  newIds: string[];
  /** Every id whose clearing this request carries, earlier batches included. */
  appliedIds: string[];
  /** The conversation these ids belong to; pass it back to forget(). */
  conversation?: string;
}

/**
 * Whether a thinking block comes at or after message `index`. On current
 * Claude models (Fable 5.1, Opus 5.5, Sonnet 5.5, Haiku 5.5) a thinking
 * block's signature binds the conversation before it: an edit to an earlier
 * message invalidates every later thinking block, and accounts created on or
 * after 2026-08-31 get a 400 for it ("... bound to a different
 * conversation"), on every retry of the same body.
 */
export function thinkingAfter(messages: unknown[], index: number): boolean {
  for (let i = Math.max(0, index); i < messages.length; i++) {
    const content = (messages[i] as { content?: unknown } | null)?.content;
    if (Array.isArray(content) && content.some((b) => b?.type === "thinking" || b?.type === "redacted_thinking")) return true;
  }
  return false;
}

/**
 * A request that sets thinking.block_binding has opted into that check (any
 * value, "drop_block" included, which silently drops the reasoning an edit
 * invalidates), so it is treated like an account known to enforce it.
 */
export function optsIntoThinkingCheck(body: Record<string, unknown>): boolean {
  const thinking = body.thinking as { block_binding?: unknown } | undefined;
  return Boolean(thinking && typeof thinking === "object" && thinking.block_binding !== undefined);
}

interface Found {
  /** Index of the message / input item that holds the result (cache breaks from here). */
  unit: number;
  id: string;
  tokens: number;
  content: unknown;
  set: (note: string) => void;
}

interface ConvState {
  last: number;
  requests: number;
}

/**
 * One request, whatever its API: the units that make up history, tool names
 * by call id, the tool results in order, and the cache lifetime to assume.
 * Anthropic Messages (Claude Code, Anthropic SDKs), OpenAI Chat Completions
 * (role "tool" messages) and OpenAI Responses (function_call_output items,
 * as Codex with an API key sends).
 */
interface View {
  format: "anthropic" | "openai-chat" | "openai-responses" | "gemini";
  units: Array<Record<string, unknown>>;
  toolName: Map<string, string>;
  results: Array<Omit<Found, "tokens">>;
  firstUser: unknown;
  /**
   * Index of the last unit the model wrote (-1 for none). Results after it
   * arrive with this request: the model has not read them yet, so they are
   * never eligible, however many there are (six parallel reads).
   */
  seenUpTo: number;
  ttlMs: number;
}

const HOUR = 3_600_000;
/**
 * Conversations' last request times are written at most this often (and on
 * flush). A record read back after a crash can be this much older than the
 * truth, so it is read as this much newer: when unsure, warm.
 */
const CONV_SAVE_MS = 60_000;

function lastIndex<T>(items: T[], pred: (x: T) => boolean): number {
  for (let i = items.length - 1; i >= 0; i--) if (pred(items[i])) return i;
  return -1;
}

export function clearedNote(tokens: number, recall = false): string {
  // Not "run it again": a cleared Bash result may come from a command with
  // side effects (a push, a delete), and repeating that would be wrong.
  // Claude Code keeps the original output in its transcript on disk, where
  // recall finds it; other clients may keep no transcript, so they are not
  // pointed there.
  if (recall) return `[context-doctor: old tool output cleared to keep context lean (~${tokens} tokens). The call above shows what ran; the full output is in the session transcript (the recall tool, or npx context-doctor recall "<words>"). Repeat the call only if it is read-only, otherwise ask the user.]`;
  return `[context-doctor: old tool output cleared to keep context lean (~${tokens} tokens). The call above shows what ran; repeat it only if it is read-only, otherwise ask the user.]`;
}

function resultTokens(content: unknown, model?: string): number {
  if (typeof content === "string") return estimateTokens(content, model);
  if (!Array.isArray(content)) return estimateTokens(JSON.stringify(content ?? ""), model);
  let n = 0;
  for (const part of content as Array<Record<string, unknown>>) {
    if (part?.type === "image" || part?.type === "image_url" || part?.type === "input_image") n += IMAGE_TOKENS;
    else if (typeof part?.text === "string") n += estimateTokens(part.text, model);
    else n += estimateTokens(JSON.stringify(part ?? ""), model);
  }
  return n;
}

/** GPT-5.6 or later (gpt-5.6-sol, gpt-6.1-sol...): the models that take prompt_cache_options. */
export function openAICacheOptionsModel(model: unknown): boolean {
  const m = /gpt-(\d+)(?:\.(\d+))?/i.exec(typeof model === "string" ? model : "");
  if (!m) return false;
  const major = Number(m[1]), minor = Number(m[2] ?? 0);
  return major > 5 || (major === 5 && minor >= 6);
}

/**
 * How long OpenAI may keep this request's prompt cached, the longest it
 * plausibly could. From OpenAI's prompt caching guide (read 2026-10-26):
 *  - GPT-5.6 and later set the lifetime with `prompt_cache_options.ttl`
 *    ("30m", the default, or "12h") and per breakpoint with
 *    `prompt_cache_breakpoint.ttl`; both are minimums ("OpenAI may retain
 *    entries longer than the requested minimum"; "12h" "does not set a
 *    deletion deadline"). Measured on the author's Codex history (gpt-5.6-sol,
 *    no ttl set): requests after 48- and 83-minute gaps read 100% from cache.
 *  - Earlier models use `prompt_cache_retention`: "in_memory" lasts "up to one
 *    hour", "24h" up to 24 hours, and organizations without Zero Data
 *    Retention default to "24h".
 *  - Any entry: "a maximum retention period of 24 hours".
 * So 24 hours, unless the request asks an earlier model for "in_memory" (one
 * hour), or uses explicit mode with no breakpoint, which caches nothing.
 * Through 0.37 this was one hour unless "24h": a GPT-5.6 cache still warm at
 * 83 minutes was called cold, and clearing it paid a rewrite.
 */
function openAITtlMs(body: Record<string, unknown>): number {
  const options = body.prompt_cache_options as { mode?: unknown; ttl?: unknown } | undefined;
  const history = JSON.stringify(body.input ?? body.messages ?? "");
  if (options && typeof options === "object" && options.mode === "explicit" && !history.includes('"prompt_cache_breakpoint"')) return 0;
  if (!openAICacheOptionsModel(body.model) && !options && body.prompt_cache_retention === "in_memory" && !history.includes('"prompt_cache_breakpoint"')) return HOUR;
  return 24 * HOUR;
}

/**
 * How long the provider may keep this prompt cached, taking the LONGER
 * possibility when unsure: calling a warm cache cold would pay a rewrite,
 * calling a cold one warm only delays a free clearing.
 *  - Anthropic: the request's own cache_control, "1h" or the 5-minute default.
 *  - OpenAI: see openAITtlMs (24 hours unless the request says otherwise).
 */
export function requestTtlMs(body: Record<string, unknown>): number {
  // Gemini: implicit caching's lifetime is not published, explicit caches default to an hour.
  if (Array.isArray(body.contents)) return HOUR;
  const openai = Array.isArray(body.input) || (Array.isArray(body.messages) && isOpenAIChat(body.messages as Array<Record<string, unknown>>));
  if (openai) return openAITtlMs(body);
  // Automatic caching puts cache_control at the top level of the request; a
  // 1-hour cache marked there was read as the 5-minute default, so autopilot
  // could clear into a cache that was still warm.
  const json = JSON.stringify(body.cache_control ?? "") + JSON.stringify(body.system ?? "") + JSON.stringify(body.tools ?? "") + JSON.stringify((body.messages as unknown[] | undefined)?.slice(-3) ?? "");
  return /"ttl"\s*:\s*"1h"/.test(json) ? HOUR : 300_000;
}

function isOpenAIChat(messages: Array<Record<string, unknown>>): boolean {
  return messages.some((m) => m?.role === "tool" || (m?.role === "assistant" && Array.isArray(m.tool_calls)) || m?.role === "system" || m?.role === "developer");
}

export function viewOf(body: Record<string, unknown>): View | undefined {
  const toolName = new Map<string, string>();
  const results: View["results"] = [];

  // Gemini generateContent: contents[].parts[] with functionCall / functionResponse.
  // Ids are optional there, so a missing one is derived. Position and the
  // first user message alone repeat whenever the same prompt runs twice, and
  // the cleared set is keyed by id: run 2 then had run 1's clearings applied
  // to its own results, newest included. The response's own content is part
  // of the derived id, so another run's result is another id unless it is
  // byte-identical at the same place (and apply() still requires it eligible).
  if (Array.isArray(body.contents)) {
    const units = body.contents as Array<Record<string, unknown>>;
    const firstUser = units.find((u) => u?.role === "user")?.parts;
    const scope = createHash("sha1").update(JSON.stringify(firstUser ?? "").slice(0, 4000)).digest("hex").slice(0, 10);
    units.forEach((u, i) => {
      if (!Array.isArray(u?.parts)) return;
      const parts = u.parts as Array<Record<string, any>>;
      parts.forEach((p, j) => {
        const call = p?.functionCall;
        const resp = p?.functionResponse;
        if (call && typeof call === "object") {
          if (typeof call.id === "string" && call.id) toolName.set(call.id, String(call.name ?? ""));
        } else if (resp && typeof resp === "object") {
          const content = createHash("sha1").update(JSON.stringify(resp.response ?? "")).digest("hex").slice(0, 12);
          const id = typeof resp.id === "string" && resp.id ? resp.id : `gemini:${scope}:${i}:${j}:${content}`;
          // The response names its tool, so it classifies on its own.
          if (!toolName.has(id)) toolName.set(id, String(resp.name ?? ""));
          results.push({ unit: i, id, content: resp.response, set: (note) => { parts[j] = { ...p, functionResponse: { ...resp, response: { output: note } } }; } });
        }
      });
    });
    const seenUpTo = lastIndex(units, (u) => u?.role === "model");
    return { format: "gemini", units, toolName, results, firstUser, seenUpTo, ttlMs: requestTtlMs(body) };
  }

  if (Array.isArray(body.input)) {
    const units = body.input as Array<Record<string, unknown>>;
    units.forEach((it, i) => {
      const t = it?.type;
      if ((t === "function_call" || t === "custom_tool_call" || t === "local_shell_call") && typeof it.call_id === "string") {
        toolName.set(it.call_id, t === "local_shell_call" ? "shell" : String(it.name ?? ""));
      } else if ((t === "function_call_output" || t === "custom_tool_call_output" || t === "local_shell_call_output") && typeof it.call_id === "string") {
        results.push({ unit: i, id: it.call_id, content: it.output, set: (note) => { units[i] = { ...it, output: note }; } });
      }
    });
    const firstUser = units.find((u) => u?.role === "user")?.content;
    // Model-written items: its tool calls, reasoning and assistant messages.
    // With previous_response_id the input holds none of them, so every result
    // in it is new to the model.
    const seenUpTo = lastIndex(units, (u) => u?.role === "assistant" || ["function_call", "custom_tool_call", "local_shell_call", "reasoning"].includes(String(u?.type)));
    return { format: "openai-responses", units, toolName, results, firstUser, seenUpTo, ttlMs: requestTtlMs(body) };
  }

  const messages = body.messages as Array<Record<string, unknown>> | undefined;
  if (!Array.isArray(messages) || messages.length === 0) return undefined;
  const firstUser = messages.find((m) => m?.role === "user")?.content;
  const seenUpTo = lastIndex(messages, (m) => m?.role === "assistant");

  if (isOpenAIChat(messages)) {
    messages.forEach((m, i) => {
      if (m?.role === "assistant" && Array.isArray(m.tool_calls)) {
        for (const c of m.tool_calls as Array<Record<string, any>>) {
          if (typeof c?.id !== "string") continue;
          toolName.set(c.id, String(c.function?.name ?? c.name ?? ""));
        }
      } else if (m?.role === "tool" && typeof m.tool_call_id === "string") {
        results.push({ unit: i, id: m.tool_call_id, content: m.content, set: (note) => { messages[i] = { ...m, content: note }; } });
      }
    });
    return { format: "openai-chat", units: messages, toolName, results, firstUser, seenUpTo, ttlMs: requestTtlMs(body) };
  }

  messages.forEach((m, i) => {
    if (!Array.isArray(m?.content)) return;
    const blocks = m.content as Array<Record<string, unknown>>;
    blocks.forEach((b, j) => {
      if (m.role === "assistant" && b?.type === "tool_use" && typeof b.id === "string") {
        toolName.set(b.id, String(b.name ?? ""));
      } else if (m.role === "user" && b?.type === "tool_result" && typeof b.tool_use_id === "string") {
        results.push({ unit: i, id: b.tool_use_id, content: b.content, set: (note) => { blocks[j] = { ...b, content: note }; } });
      }
    });
  });
  return { format: "anthropic", units: messages, toolName, results, firstUser, seenUpTo, ttlMs: requestTtlMs(body) };
}

/**
 * A conversation's identity, the same from its first request on: the first
 * user message, plus the client's own session tag when it sends one
 * (Anthropic metadata.user_id, which Claude Code fills per session; OpenAI
 * prompt_cache_key). The first user message is read without cache_control:
 * Claude Code marks the last message, which on request 1 is the first one,
 * and moves the marker on request 2. Through 0.31.1 the key also held the
 * first tool call id, so request 2 (the first tool round) was a new,
 * never-seen conversation, called cold eight seconds after request 1.
 * Two sessions that open with the same message and send no tag share a key;
 * that only ever makes one look warm when the other is, the safe direction.
 * The model is left out on purpose: switching models mid-session keeps the
 * conversation (and the cleared set) but not the cache, which the TTL check
 * cannot see, so a model switch is treated as warm, the safe direction.
 */
function conversationKey(view: View, body: Record<string, unknown>): string {
  const first = JSON.stringify(view.firstUser ?? "", (k, v) => (k === "cache_control" ? undefined : v)) ?? "";
  const h = createHash("sha1").update(first.slice(0, 4000));
  const tag = (body.metadata as { user_id?: unknown } | undefined)?.user_id ?? body.prompt_cache_key;
  if (typeof tag === "string") h.update("\0").update(tag);
  return h.digest("hex");
}

/**
 * Cleared ids and result sizes are per conversation. Tool call ids are only
 * unique within one: OpenAI-compatible clients number them call_0, call_1…
 * in every conversation, so a global map cleared a new, warm conversation's
 * results on its first request because another conversation had cleared
 * the same ids, and reported the other conversation's sizes for them.
 */
function scoped(conversation: string, id: string): string {
  return `${conversation}\u0000${id}`;
}

export class AutoClearer {
  /** Cleared results, keyed by scoped(conversation, id): tokens the output had. */
  private cleared = new Map<string, number>();
  /** Tool results never change once sent, so their size is computed once per conversation and id. */
  private sizes = new Map<string, number>();
  private convs = new Map<string, ConvState>();
  private opts: Required<Omit<AutoClearOptions, "statePath">> & { statePath?: string };
  private dirty = false;
  /** Conversation times changed since the last save (written at most every CONV_SAVE_MS, or on flush). */
  private convsDirty = false;
  private lastSave = 0;
  /** Accounts (salted credential hashes from the caller) whose API rejected a history autopilot edited. */
  private rejecting = new Set<string>();

  constructor(options: AutoClearOptions = {}) {
    this.opts = {
      keepRecent: options.keepRecent ?? 3,
      minClearTokens: options.minClearTokens ?? 20_000,
      paybackSafety: options.paybackSafety ?? 0,
      unseenIsWarm: options.unseenIsWarm ?? false,
      statePath: options.statePath,
    };
    this.load();
  }

  /**
   * Rewrite `body` in place: an Anthropic Messages, OpenAI Chat Completions or
   * OpenAI Responses request. Never throws; anything unrecognised is left alone.
   * `account` names the credential the request carries (the proxy passes a
   * salted hash), for accounts whose API rejects edited history.
   * `recallHint`: the client keeps a transcript recall can search (Claude
   * Code); the cleared note then says where the full output still is. It
   * must be the same on every request of a conversation (the note is part of
   * the cached prefix), which a client's User-Agent is.
   */
  apply(body: Record<string, unknown>, now = Date.now(), modelHint?: string, account?: string, opts: { recallHint?: boolean } = {}): AutoClearResult {
    const none = (reason: string, cold = false): AutoClearResult => ({ changed: false, newlyCleared: 0, tokensRemoved: 0, cold, reason, firstChanged: -1, newIds: [], appliedIds: [] });
    try {
      const view = viewOf(body);
      if (!view) return none("no messages");
      // Gemini puts the model in the URL, not the body; the proxy passes it.
      const model = typeof body.model === "string" ? body.model : modelHint;

      const key = conversationKey(view, body);
      const conv = this.convs.get(key);
      const cold = conv ? now - conv.last > view.ttlMs : !this.opts.unseenIsWarm;
      // Delete first so the map stays in last-used order and the cap evicts idle conversations.
      this.convs.delete(key);
      this.convs.set(key, { last: now, requests: (conv?.requests ?? 0) + 1 });
      if (this.convs.size > 2000) this.convs.delete(this.convs.keys().next().value!);
      this.convsDirty = true;

      const results: Found[] = view.results.map((r) => {
        const sk = scoped(key, r.id);
        let tokens = this.sizes.get(sk);
        if (tokens === undefined) {
          tokens = resultTokens(r.content, model);
          this.sizes.set(sk, tokens);
          if (this.sizes.size > 100_000) this.sizes.delete(this.sizes.keys().next().value!);
        }
        return { ...r, tokens };
      });

      // Results that arrive with this request (after the model's last turn)
      // are not eligible however many there are: the model has not read them.
      const eligible = results.slice(0, Math.max(0, results.length - this.opts.keepRecent))
        .filter((r) => r.unit <= view.seenUpTo && CLEARABLE_TOOLS.has(view.toolName.get(r.id) ?? ""));
      const eligibleIds = new Set(eligible.map((r) => r.id));
      const pending = eligible.filter((r) => !this.cleared.has(scoped(key, r.id)) && r.tokens > 200);
      const pendingTokens = pending.reduce((n, r) => n + r.tokens, 0);

      let reason = "nothing to clear";
      let taken: Found[] = [];
      if (pendingTokens >= this.opts.minClearTokens) {
        if (cold) {
          taken = pending;
          reason = "cache cold: cleared for free";
        } else if (this.opts.paybackSafety > 0 && this.shouldClearWarm(view.units, pending, pendingTokens, model, (conv?.requests ?? 0) + 1)) {
          taken = pending;
          reason = "cache warm: saving repays the rewrite";
        } else {
          reason = "cache warm: waiting, rewrite would not pay back yet";
        }
      } else if (pendingTokens > 0) {
        reason = `waiting for a ${Math.round(this.opts.minClearTokens / 1000)}k batch`;
      }
      // An account that rejects edited history gets no NEW clearing a
      // thinking block comes after: that block is bound to the history as it
      // was. Clearings already sent keep being applied, because thinking
      // generated since then is bound to the cleared history; dropping them
      // would break the conversation the other way.
      if (taken.length && (this.rejectsEdits(account) || optsIntoThinkingCheck(body)) && thinkingAfter(view.units, Math.min(...taken.map((r) => r.unit)))) {
        taken = [];
        reason = "thinking blocks follow the stale output and this account rejects edited history: left as is";
      }
      for (const r of taken) this.cleared.set(scoped(key, r.id), r.tokens);
      if (taken.length) this.dirty = true;

      // Apply every clearing ever decided for this conversation, so the
      // prefix is identical to what was sent last time. A remembered id must
      // still be eligible here: a derived id (Gemini without ids) can recur in
      // another conversation, where it must not cost that one its newest result.
      let removed = 0;
      let changed = false;
      let firstChanged = -1;
      const appliedIds: string[] = [];
      for (const r of results) {
        const sk = scoped(key, r.id);
        if (!this.cleared.has(sk) || !eligibleIds.has(r.id)) continue;
        const note = clearedNote(this.cleared.get(sk)!, opts.recallHint === true);
        if (r.content === note) continue;
        removed += Math.max(0, r.tokens - estimateTokens(note, model));
        r.set(note);
        changed = true;
        appliedIds.push(r.id);
        if (firstChanged === -1 || r.unit < firstChanged) firstChanged = r.unit;
      }
      this.save();
      return { changed, newlyCleared: taken.length, tokensRemoved: removed, cold, reason, firstChanged, newIds: taken.map((r) => r.id), appliedIds, conversation: key };
    } catch {
      return none("error: request forwarded unchanged");
    }
  }

  /**
   * Warm cache: clearing rewrites everything after the first cleared result
   * at the write rate (1.25x instead of 0.1x: 1.15x extra, once), and saves
   * the cleared tokens at the read rate (0.1x) on every later request.
   * Later requests are estimated as the number made so far (a conversation's
   * age is the best predictor of how long it keeps going), and the saving must
   * cover the rewrite `paybackSafety` times over.
   */
  private shouldClearWarm(messages: Array<Record<string, unknown>>, pending: Found[], pendingTokens: number, model: string | undefined, requestsSoFar: number): boolean {
    const first = Math.min(...pending.map((r) => r.unit));
    let suffix = -pendingTokens;
    for (let i = first; i < messages.length; i++) suffix += estimateTokens(JSON.stringify(messages[i]), model);
    const rewriteCost = 1.15 * Math.max(0, suffix);
    const saving = 0.1 * pendingTokens * requestsSoFar;
    return saving >= this.opts.paybackSafety * rewriteCost;
  }

  /** Write pending state now (the proxy calls this on a timer and before it exits). */
  flush(): void {
    this.save(true);
  }

  /** Whether this account's API has rejected a history autopilot edited (see thinkingAfter). */
  rejectsEdits(account?: string): boolean {
    return account !== undefined && this.rejecting.has(account);
  }

  /** Remember, across restarts, that this account's API rejects edited history. */
  noteEditsRejected(account: string): void {
    if (this.rejecting.has(account)) return;
    this.rejecting.add(account);
    this.dirty = true;
    this.save();
  }

  /**
   * Stop applying these clearings: the API refused the request that carried
   * them, and any thinking it produces from now on is bound to the history
   * without them.
   */
  forget(ids: string[], conversation?: string): void {
    let any = false;
    if (conversation !== undefined) {
      for (const id of ids) any = this.cleared.delete(scoped(conversation, id)) || any;
    } else {
      // No conversation named: these ids in every conversation.
      const wanted = new Set(ids);
      for (const k of [...this.cleared.keys()]) {
        if (wanted.has(k.slice(k.indexOf("\u0000") + 1))) any = this.cleared.delete(k) || any;
      }
    }
    if (any) {
      this.dirty = true;
      this.save();
    }
  }

  private load(): void {
    if (!this.opts.statePath || !existsSync(this.opts.statePath)) return;
    try {
      const data = JSON.parse(readFileSync(this.opts.statePath, "utf8")) as {
        clearedByConversation?: Array<[string, string, number]>;
        convs?: Array<[string, number, number]>;
        rejectsEdits?: string[];
      };
      // Through 0.34 cleared ids were global (`cleared: [id, tokens][]`) and
      // say nothing about which conversation they belong to; they are not
      // carried over. An open conversation re-clears at its next cold gap.
      for (const entry of Array.isArray(data.clearedByConversation) ? data.clearedByConversation : []) {
        if (!Array.isArray(entry)) continue;
        const [conv, id, tokens] = entry;
        if (typeof conv === "string" && typeof id === "string" && typeof tokens === "number") this.cleared.set(scoped(conv, id), tokens);
      }
      // Each conversation's last request time, so a restart does not make
      // every open conversation "unseen" (cold) and rewrite a warm cache.
      for (const entry of Array.isArray(data.convs) ? data.convs : []) {
        if (!Array.isArray(entry)) continue;
        const [key, last, requests] = entry;
        if (typeof key === "string" && typeof last === "number") this.convs.set(key, { last: last + CONV_SAVE_MS, requests: Number(requests) || 1 });
      }
      if (Array.isArray(data.rejectsEdits)) for (const account of data.rejectsEdits) if (typeof account === "string") this.rejecting.add(account);
    } catch {
      /* a corrupt state file only means results may be re-cleared once */
    }
  }

  private save(force = false): void {
    if (!this.opts.statePath) return;
    const due = this.convsDirty && (force || Date.now() - this.lastSave >= CONV_SAVE_MS);
    if (!this.dirty && !due) return;
    this.dirty = false;
    this.convsDirty = false;
    this.lastSave = Date.now();
    try {
      // Newest 50k ids: far more than any live session holds.
      const entries = [...this.cleared.entries()].slice(-50_000).map(([k, tokens]) => {
        const at = k.indexOf("\u0000");
        return [k.slice(0, at), k.slice(at + 1), tokens];
      });
      const convs = [...this.convs.entries()].map(([k, c]) => [k, c.last, c.requests]);
      mkdirSync(dirname(this.opts.statePath), { recursive: true });
      writeFileSync(this.opts.statePath, JSON.stringify({ clearedByConversation: entries, convs, rejectsEdits: [...this.rejecting] }));
    } catch {
      /* persistence is best effort */
    }
  }
}
